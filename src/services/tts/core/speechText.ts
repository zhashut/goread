/**
 * 朗读文本过滤
 *
 * 部分语音引擎会把引号逐字朗读出来（如读出「双引号」），因此在把文本交给引擎前
 * 统一剔除引号类符号；逗号、句号等承担停顿的标点必须保留，否则朗读会失去句读节奏。
 *
 * 注意：
 * - 过滤仅作用于朗读文本；高亮与跟读定位依赖原文 anchor，不受影响；
 * - 剔除后前后文字直接拼接（如 `他说“你好”` → `他说你好`），不影响朗读；
 * - 整段只有引号时会得到空串，调用方需据此跳过该片段。
 */

/** 引号类符号：直引号、反引号、弯引号、书名式角引号与全角引号 */
const SPEECH_QUOTES = /["'`«»‘’‚‛“”„‟‹›「」『』〝〞〟＂＇｢｣]/gu;

/**
 * 剔除引号类符号，返回可朗读文本（并去除首尾空白）
 * @param text 原文片段
 * @returns 去掉引号后的文本；整段只有引号时为空串
 */
export const stripSpeechQuotes = (text: string): string =>
  text.replace(SPEECH_QUOTES, '').trim();
